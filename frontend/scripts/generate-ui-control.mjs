import { readFileSync, writeFileSync } from 'node:fs'
const contract = JSON.parse(readFileSync(new URL('../../agent_go/cmd/server/ui_control_contract.json', import.meta.url), 'utf8'))
const output = `// Generated by scripts/generate-ui-control.mjs; do not edit.\nexport const UI_CONTROL_CONTRACT = ${JSON.stringify(contract, null, 2)} as const\n`
const path = new URL('../src/platform/ui-control/contract.generated.ts', import.meta.url)
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw new Error('UI control contract is stale; run node scripts/generate-ui-control.mjs')
} else writeFileSync(path, output)
